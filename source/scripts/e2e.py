import asyncio, json, re, sys
from playwright.async_api import async_playwright, expect

URL = 'http://127.0.0.1:4173/index.html'
ok = []; fail = []
def check(cond, name):
    (ok if cond else fail).append(name); print(('✅' if cond else '❌'), name)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
        pg = await ctx.new_page()
        errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: m.type == 'error' and 'fonts.g' not in m.text and 'ERR_TUNNEL' not in m.text and errs.append(m.text))
        await pg.goto(URL)

        # ---------- Onboarding ----------
        await pg.get_by_label('Nom de ton entreprise / activité').fill('Studio Test')
        await pg.get_by_label('Ton nom').fill('Nathan Test')
        await pg.get_by_role('button', name='Continuer').click()
        await pg.get_by_label('Tarif horaire habituel').fill('40')
        await pg.get_by_role('switch', name=re.compile('Je facture la TVA')).click()
        await pg.get_by_label(re.compile('Ton taux principal')).fill('21')
        await pg.get_by_role('button', name='Continuer').click()
        await pg.get_by_role('button', name='Montage vidéo').click()
        await pg.get_by_role('button', name='Création de sites Internet').click()
        await pg.get_by_role('switch', name=re.compile('démonstration')).click()
        await pg.get_by_role('button', name="C'est parti").click()
        await pg.wait_for_timeout(400)
        st = await pg.evaluate("JSON.parse(localStorage.getItem('workprice-pro:v1:default'))")
        check(st['settings']['company']['name'] == 'Studio Test', 'onboarding : nom enregistré')
        check(st['settings']['vat']['enabled'] and st['settings']['vat']['rates'] == [21], 'onboarding : TVA 21 % configurée')
        check(len(st['trades']) == 2, f"onboarding : 2 métiers créés ({len(st['trades'])})")
        check(len(st['clients']) == 6 and len(st['invoices']) > 5, f"démo : {len(st['clients'])} clients, {len(st['invoices'])} factures")
        await pg.screenshot(path='out/d-dashboard.png', full_page=True)
        ca = await pg.locator('text=Chiffre d\'affaires HT').locator('xpath=../..').inner_text()
        check('€' in ca and '0,00 €\n' not in ca, 'dashboard : CA affiché')
        # filtres de période
        for lab in ['Ce mois', 'Tout', 'Cette année', '12 mois']:
            await pg.get_by_role('button', name=lab, exact=True).click()
        # survol du graphique
        await pg.locator('svg[aria-label="Graphique des revenus"]').hover(position={'x': 600, 'y': 120})
        check(await pg.locator('text=Bénéfice estimé').count() >= 2, 'dashboard : graphique interactif (infobulle)')

        # ---------- Calculateur : exemple du cahier des charges ----------
        await pg.goto(URL + '#/calculator')
        await pg.locator('[data-method=custom]').click()
        await pg.get_by_label(re.compile('Temps total estimé')).fill('0')
        await pg.get_by_role('button', name='Ligne de coût').click()
        await pg.get_by_label('Montant').fill('50')
        await pg.get_by_label('Marge souhaitée').fill('40')
        await pg.get_by_role('button', name='Sur prix de vente').click()
        price = await pg.get_by_test_id('price-ht').inner_text()
        check('83,33' in price, f'calcul : 50 € / (1 − 40 %) = {price.strip()}')
        await pg.get_by_role('button', name='Sur coût').click()
        price = await pg.get_by_test_id('price-ht').inner_text()
        check('70,00' in price, f'calcul : marge sur coût 40 % = {price.strip()}')

        # Horaire complet
        await pg.get_by_role('button', name='Réinitialiser').click()
        await pg.get_by_label('Nom de la prestation').fill('Montage YouTube test')
        await pg.locator('[data-method=hourly]').click()
        await pg.get_by_label('Quantité', exact=True).fill('2')
        await pg.get_by_label(re.compile('^Temps par unité')).fill('3')
        await pg.get_by_label('Tarif horaire').fill('40')
        await pg.get_by_label('Matériel utilisé').fill('20')
        await pg.get_by_label('Marge souhaitée').fill('20')
        await pg.get_by_role('button', name='Sur coût').click()
        await pg.get_by_label('Majoration pour urgence').fill('10')
        price = await pg.get_by_test_id('price-ht').inner_text()
        # (6h×40 + 20) × 1,2 × 1,1 = 343,20
        check('343,20' in price, f'calcul horaire + frais + marge + urgence = {price.strip()}')
        res = await pg.get_by_test_id('result').inner_text()
        check('TTC' in res and '415,27' in res, 'calcul : TVA 21 % → TTC 415,27 €')
        # Forfait sous le coût -> alerte
        await pg.locator('[data-method=flat]').click()
        await pg.get_by_label('Prix forfaitaire HT').fill('100')
        check(await pg.get_by_test_id('warnings').count() == 1, 'forfait sous le coût : alerte affichée')
        await pg.get_by_role('button', name=re.compile('Appliquer le prix conseillé')).click()
        price2 = await pg.get_by_test_id('price-ht').inner_text()
        check('184,80' in price2, f'prix conseillé appliqué = {price2.strip()}')
        await pg.locator('[data-method=hourly]').click()
        await pg.get_by_role('button', name='Enregistrer', exact=True).click()
        await pg.screenshot(path='out/d-calculator.png', full_page=True)
        # dans un métier
        await pg.get_by_role('button', name='Dans un métier').click()
        await pg.get_by_role('dialog').get_by_role('button', name='Enregistrer').click()
        st = await pg.evaluate("JSON.parse(localStorage.getItem('workprice-pro:v1:default'))")
        check(len(st['calculations']) == 1, 'historique : calcul enregistré')
        check(any(s['name'] == 'Montage YouTube test' for t in st['trades'] for s in t['services']), 'prestation enregistrée dans un métier')

        # ---------- Devis depuis le calcul ----------
        await pg.get_by_role('button', name='Créer un devis avec ce prix').click()
        await pg.wait_for_url(re.compile('#/quotes/'))
        num = await pg.get_by_test_id('doc-number').inner_text()
        check(re.search(r'DEV-\d{4}-\d{4}', num) is not None, f'devis créé avec numéro auto : {num}')
        tot = await pg.get_by_test_id('totals').inner_text()
        check('343,20' in tot and '415,27' in tot, 'devis : totaux HT/TTC repris du calcul')
        await pg.get_by_label('Client', exact=True).select_option(index=1)
        await pg.get_by_role('button', name='Ligne', exact=True).click()
        lines = pg.get_by_test_id('line')
        await lines.nth(1).get_by_label('Description').fill('Miniature YouTube')
        await lines.nth(1).get_by_label('Quantité').fill('2')
        await lines.nth(1).get_by_label('Prix unitaire HT').fill('20')
        await pg.get_by_label('Remise globale').fill('10')
        tot = await pg.get_by_test_id('total-ttc').inner_text()
        # (343,20 + 40) × 0,9 = 344,88 → TVA 72,42 → 417,30
        check('417,30' in tot, f'devis : 2e ligne + remise 10 % → TTC {tot.strip()}')
        await pg.get_by_role('button', name='Catalogue').click()
        await pg.get_by_role('dialog').get_by_role('button', name=re.compile('Pack 5 vidéos')).click()
        check(await lines.count() == 3, 'devis : ajout d\'un pack depuis le catalogue')
        # PDF
        async with pg.expect_download() as dl:
            await pg.get_by_role('button', name='Télécharger PDF').click()
        d = await dl.value
        path = await d.path()
        data = open(path, 'rb').read()
        check(data[:4] == b'%PDF' and len(data) > 2000, f'PDF devis téléchargé ({d.suggested_filename}, {len(data)} o)')
        open('out/e2e-devis.pdf', 'wb').write(data)
        await pg.screenshot(path='out/d-quote.png', full_page=True)
        await pg.get_by_role('button', name='Marquer envoyé').click()
        await pg.get_by_role('button', name='Accepté').click()
        await pg.get_by_role('button', name='Transformer en facture').click()
        await pg.wait_for_url(re.compile('#/invoices/'))
        await pg.wait_for_timeout(300)
        check('brouillon' in (await pg.get_by_test_id('doc-number').inner_text()), 'facture brouillon créée depuis le devis (sans numéro)')
        await pg.get_by_role('button', name='Émettre la facture').click()
        await pg.get_by_role('dialog').get_by_role('button', name='Émettre').click()
        inum = await pg.get_by_test_id('doc-number').inner_text()
        check(re.search(r'FAC-\d{4}-\d{4}', inum) is not None, f'facture émise : {inum}')
        check(await pg.get_by_label('Description').first.is_disabled(), 'facture émise verrouillée')
        await pg.get_by_role('button', name='Paiement reçu').click()
        await pg.get_by_role('dialog').get_by_label('Montant reçu').fill('100')
        await pg.get_by_role('dialog').get_by_role('button', name='Enregistrer').click()
        check(await pg.locator('text=Partiel').count() >= 1, 'paiement partiel → statut Partiel')
        await pg.get_by_role('button', name='Paiement reçu').click()
        await pg.get_by_role('dialog').get_by_role('button', name='Enregistrer').click()
        await pg.wait_for_timeout(200)
        check(await pg.locator('main >> text=Payée').count() >= 1, 'solde payé → statut Payée')
        async with pg.expect_download() as dl:
            await pg.get_by_role('button', name='Télécharger PDF').click()
        d = await dl.value
        open('out/e2e-facture.pdf', 'wb').write(open(await d.path(), 'rb').read())
        check(d.suggested_filename.startswith('Facture_FAC-'), f'PDF facture : {d.suggested_filename}')

        # ---------- Clients ----------
        await pg.goto(URL + '#/clients')
        await pg.get_by_role('button', name='Nouveau client').click()
        dlg = pg.get_by_role('dialog')
        await dlg.get_by_label('Nom du contact *').fill('Jean Testeur')
        await dlg.get_by_label('Entreprise', exact=True).fill('Testeur SA')
        await dlg.get_by_label('E-mail').fill('jean@test.be')
        await dlg.get_by_role('button', name='Enregistrer').click()
        await pg.wait_for_url(re.compile('#/clients/'))
        await pg.wait_for_timeout(300)
        check(await pg.locator('main h1', has_text='Testeur SA').count() == 1, 'client créé et fiche ouverte')
        await pg.goto(URL + '#/clients')
        await pg.get_by_placeholder(re.compile('Rechercher nom')).fill('testeur')
        check(await pg.locator('main a[href^="#/clients/"]').count() == 1, 'recherche client')
        await pg.get_by_placeholder(re.compile('Rechercher nom')).fill('')
        await pg.get_by_role('button', name='Avec impayés').click()
        n_unpaid = await pg.locator('main a[href^="#/clients/"]').count()
        check(n_unpaid >= 1, f'filtre clients avec impayés ({n_unpaid})')
        await pg.get_by_role('button', name='Tous', exact=True).click()
        await pg.locator('main a[href^="#/clients/"]').first.click()
        await pg.screenshot(path='out/d-client.png', full_page=True)
        check(await pg.locator('text=Historique des prestations').count() == 1, 'fiche client : historiques')

        # ---------- Métiers / packs ----------
        await pg.goto(URL + '#/trades')
        await pg.locator('main a[href^="#/trades/"]').first.click()
        await pg.get_by_role('button', name=re.compile('Packs & abonnements')).click()
        await pg.get_by_role('button', name='Nouveau pack').click()
        dlg = pg.get_by_role('dialog')
        await dlg.get_by_label('Nom du pack').fill('Pack 10 vidéos')
        await dlg.get_by_label('Nombre de prestations').fill('10')
        await dlg.get_by_label('Prix individuel HT (hors pack)').fill('70')
        await dlg.get_by_label('Prix total HT').fill('450')
        txt = await dlg.inner_text()
        check('45,00' in txt and '250,00' in txt, 'pack : prix unitaire 45 € et économie 250 € calculés')
        await dlg.get_by_role('button', name='Enregistrer le pack').click()
        check(await pg.locator('text=Pack 10 vidéos').count() == 1, 'pack enregistré')
        await pg.screenshot(path='out/d-trade.png', full_page=True)
        await pg.get_by_role('button', name=re.compile('^Options')).click()
        await pg.get_by_role('button', name='Ajouter').click()
        await pg.get_by_label("Nom de l'option").last.fill('Option test')
        await pg.goto(URL + '#/trades')
        await pg.get_by_role('button', name='Ajouter un métier').click()
        await pg.get_by_role('button', name=re.compile('Métier vierge')).click()
        await pg.get_by_label('Nom du métier').fill('Coach sportif')
        await pg.goto(URL + '#/trades')
        check(await pg.locator('text=Coach sportif').count() == 1, 'métier personnalisé créé')

        # ---------- Listes ----------
        await pg.goto(URL + '#/invoices')
        await pg.get_by_role('button', name='Impayées').click()
        await pg.screenshot(path='out/d-invoices.png', full_page=True)
        await pg.goto(URL + '#/quotes')
        await pg.screenshot(path='out/d-quotes.png', full_page=True)

        # ---------- Persistance ----------
        before = await pg.evaluate("localStorage.getItem('workprice-pro:v1:default').length")
        await pg.reload()
        await pg.wait_for_timeout(300)
        check(await pg.locator('text=Studio Test').count() >= 1, f'persistance après rechargement ({before} o)')

        # ---------- Sauvegarde / restauration ----------
        await pg.goto(URL + '#/settings')
        async with pg.expect_download() as dl:
            await pg.get_by_role('button', name=re.compile('Exporter une sauvegarde')).click()
        bk = await (await dl.value).path()
        backup = json.load(open(bk))
        check(len(backup['clients']) == 7, f"sauvegarde exportée ({len(backup['clients'])} clients)")
        await pg.get_by_role('button', name='Tout effacer').click()
        await pg.get_by_role('dialog').get_by_role('button', name='Tout effacer').click()
        await pg.wait_for_timeout(300)
        st = await pg.evaluate("JSON.parse(localStorage.getItem('workprice-pro:v1:default'))")
        check(len(st['clients']) == 0, 'tout effacer')
        await pg.get_by_role('button', name='Passer').click()
        await pg.goto(URL + '#/settings')
        async with pg.expect_file_chooser() as fc:
            await pg.get_by_role('button', name='Restaurer une sauvegarde').click()
        await (await fc.value).set_files(bk)
        await pg.get_by_role('dialog').get_by_role('button', name='Restaurer').click()
        await pg.wait_for_timeout(300)
        st = await pg.evaluate("JSON.parse(localStorage.getItem('workprice-pro:v1:default'))")
        check(len(st['clients']) == 7 and len(st['invoices']) == len(backup['invoices']), 'restauration complète')
        # logo
        async with pg.expect_file_chooser() as fc:
            await pg.get_by_role('button', name='Ajouter un logo').click()
        await (await fc.value).set_files('out/logo-test.png')
        await pg.wait_for_timeout(500)
        st = await pg.evaluate("JSON.parse(localStorage.getItem('workprice-pro:v1:default'))")
        check(st['settings']['company']['logo'].startswith('data:image/png'), 'logo importé')
        await pg.get_by_role('button', name='☀️ Clair').click()
        await pg.screenshot(path='out/d-settings-light.png')
        await pg.get_by_role('button', name='🌙 Sombre').click()

        # PDF avec logo, depuis une facture
        await pg.goto(URL + '#/invoices')
        await pg.locator('main table tbody tr').first.click()
        async with pg.expect_download() as dl:
            await pg.get_by_role('button', name='Télécharger PDF').click()
        open('out/e2e-facture-logo.pdf', 'wb').write(open(await (await dl.value).path(), 'rb').read())
        check(True, 'PDF avec logo généré')

        # ---------- Responsive mobile ----------
        m = await b.new_page(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
        m.on('pageerror', lambda e: errs.append('mobile: ' + str(e)))
        await m.goto(URL)
        await m.evaluate(f"localStorage.setItem('workprice-pro:v1:default', {json.dumps(json.dumps(st))})")
        await m.reload()
        for route in ['dashboard', 'calculator', 'trades', 'clients', 'quotes', 'invoices', 'settings']:
            await m.goto(URL + '#/' + route)
            await m.wait_for_timeout(600)
            over = await m.evaluate('document.documentElement.scrollWidth - window.innerWidth')
            check(over <= 1, f'mobile #{route} : pas de débordement horizontal ({over}px)')
            await m.screenshot(path=f'out/m-{route}.png')
        await m.goto(URL + '#/quotes')
        await m.locator('main a[href^="#/quotes/"]').first.click()
        await m.wait_for_timeout(250)
        over = await m.evaluate('document.documentElement.scrollWidth - window.innerWidth')
        check(over <= 1, f'mobile éditeur de devis : pas de débordement ({over}px)')
        await m.screenshot(path='out/m-quote.png', full_page=True)
        await m.goto(URL + '#/dashboard')
        await m.get_by_role('button', name='Ouvrir le menu').click()
        check(await m.get_by_role('link', name='Paramètres').is_visible(), 'mobile : menu latéral')
        # tablette
        t = await b.new_page(viewport={'width': 820, 'height': 1180})
        await t.goto(URL)
        await t.evaluate(f"localStorage.setItem('workprice-pro:v1:default', {json.dumps(json.dumps(st))})")
        await t.reload()
        await t.goto(URL + '#/calculator')
        await t.wait_for_timeout(250)
        check(await t.evaluate('document.documentElement.scrollWidth - window.innerWidth') <= 1, 'tablette : calculateur sans débordement')
        await t.screenshot(path='out/t-calculator.png')

        check(not errs, f'aucune erreur JavaScript ({errs[:3]})')
        await b.close()
    print(f'\n{len(ok)} OK / {len(fail)} échec(s)')
    if fail: print('ÉCHECS :', fail); sys.exit(1)

asyncio.run(main())
